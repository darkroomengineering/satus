import type { IntegrationStatus } from './deployment-checklist'

/** A `null` list means its scan failed and the section renders a fallback line. */
export interface InventoryData {
  date: string
  integrations: IntegrationStatus[]
  uiComponents: string[] | null
  layoutComponents: string[] | null
  effectComponents: string[] | null
  /** Page routes, examples excluded. */
  pages: string[] | null
}

function pushComponentSection(
  lines: string[],
  heading: string,
  components: string[] | null,
  scanErrorLine: string
): void {
  lines.push(heading)
  lines.push('')
  if (components === null) {
    lines.push(scanErrorLine)
  } else {
    for (const name of components) {
      lines.push(`- \`${name}\``)
    }
  }
  lines.push('')
}

export function renderInventory({
  date,
  integrations,
  uiComponents,
  layoutComponents,
  effectComponents,
  pages,
}: InventoryData): string {
  const lines: string[] = []

  lines.push('# Component Inventory')
  lines.push('')
  lines.push(`Generated: ${date}`)
  lines.push('')
  // A later `setup:project` integration strip leaves this snapshot stale with
  // no signal, so it describes itself.
  lines.push(
    `> Snapshot generated by \`bun run handoff\` on ${date}. Regenerate after any later integration changes by re-running \`bun run handoff\`.`
  )
  lines.push('')

  lines.push('## Installed Integrations')
  lines.push('')
  if (integrations.length > 0) {
    for (const { name, configured } of integrations) {
      lines.push(
        configured ? `- ${name}` : `- ${name} — installed, needs configuration`
      )
    }
  } else {
    lines.push('- None installed')
  }
  lines.push('')

  pushComponentSection(
    lines,
    '## UI Components',
    uiComponents,
    '- Could not scan components'
  )
  pushComponentSection(
    lines,
    '## Layout Components',
    layoutComponents,
    '- Could not scan layout components'
  )
  pushComponentSection(
    lines,
    '## Effect Components',
    effectComponents,
    '- Could not scan effect components'
  )

  lines.push('## Pages')
  lines.push('')
  if (pages === null) {
    lines.push('- Could not scan pages')
  } else {
    for (const route of pages) {
      lines.push(`- \`/${route}\``)
    }
  }
  // Trailing blank line so the joined text ends in `\n`; a document without
  // one fails `oxfmt --check`.
  lines.push('')

  return lines.join('\n')
}
