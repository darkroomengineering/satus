import { defineConfig } from 'oxfmt'

// Must be named `oxfmt.config.ts` (`.oxfmtrc.ts` is not discovered). Every
// house-style option is explicit because oxfmt's defaults differ.
export default defineConfig({
  printWidth: 80,
  tabWidth: 2,
  useTabs: false,
  semi: false,
  singleQuote: true,
  trailingComma: 'es5',
  arrowParens: 'always',
  endOfLine: 'lf',
  // Stops Markdown prose being re-wrapped, which keeps the .md diff to
  // whitespace and table normalisation instead of a full rewrite.
  proseWrap: 'preserve',
  overrides: [
    {
      // Code blocks in docs stay as written. Formatting them sorts imports
      // away from the `// Layout` style comments that label them, and the
      // Tailwind sorter orders classes there unlike it does in .tsx files.
      files: ['**/*.md'],
      options: { embeddedLanguageFormatting: 'off' },
    },
  ],

  // Both sorters are off by default.
  sortImports: {
    groups: [
      'builtin',
      'external',
      ['internal', 'subpath'],
      ['parent', 'sibling', 'index'],
      'style',
      'unknown',
    ],
    // A prefix list, not a regex. `["^@/.*"]` matches nothing and silently
    // lumps every @/ import in with the external packages.
    internalPattern: ['@/'],
    ignoreCase: true,
    // Keeps side-effect imports where they are. The `style` group above is what
    // holds app/layout.tsx's trailing `import '@/lib/styles/css/index.css'` at
    // the bottom of the block.
    sortSideEffects: false,
  },

  sortTailwindcss: {
    // Resolves the @theme tokens (custom `dt:` breakpoint, `primary` colour).
    stylesheet: './lib/styles/css/index.css',
    functions: ['cn', 'clsx'],
  },

  // sortPackageJson is on by default; this keeps the human-curated script order.
  sortPackageJson: {
    sortScripts: false,
  },

  ignorePatterns: [
    'node_modules/**',
    '.next/**',
    'dist/**',
    'public/**',
    '.vercel/**',
    'bun.lock',
    // Generated by `bun run setup:styles`, and tab-indented on purpose.
    // Formatting them puts the generator and the formatter in a permanent fight.
    'lib/styles/css/tailwind.css',
    'lib/styles/css/root.css',
    // Generated by `bun run sanity:typegen`.
    'lib/integrations/sanity/sanity.types.ts',
    // Written by `sanity dev` / `sanity build` run from the Studio folder.
    'lib/integrations/sanity/.sanity/**',
    'lib/integrations/sanity/node_modules/**',
    'lib/integrations/sanity/dist/**',
    // Vendored from dmmulroy/anti-slop; keeps upstream formatting so a
    // sync diff against upstream stays readable.
    'tools/oxlint/anti-slop/**',
    // Generated by `bun run generate:manifest`.
    'COMPONENTS.md',
    // Append-only; reflowing it destroys history readability.
    'CHANGELOG.md',
  ],
})
